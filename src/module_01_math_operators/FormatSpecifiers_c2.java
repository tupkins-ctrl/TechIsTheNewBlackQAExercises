package module_01_math_operators;

public class FormatSpecifiers_c2 {
    public static void main(String[] args) {
        char e = 'E';
        char h = 'H';
        char f = 'F';

        System.out.printf("%c - means %s\n", e, "an empty tank");
        System.out.printf("%c - means %s\n", h, "a half tank");
        System.out.printf("%c - means %s\n", f, "a full tank");
    }
}
